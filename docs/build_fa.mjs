// node build_fa.mjs <svgs/solid dir> <metadata json> <out js>
// Packs Font Awesome Free's solid icons into one file for DriveCraft's icon picker.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
const [dir, meta, out] = process.argv.slice(2);
const m = JSON.parse(readFileSync(meta, "utf8"));
const byShape = new Map();
let skipped = 0;
for (const f of readdirSync(dir).filter((f) => f.endsWith(".svg")).sort()) {
  const svg = readFileSync(`${dir}/${f}`, "utf8");
  const box = /viewBox="0 0 (\d+(?:\.\d+)?) (\d+(?:\.\d+)?)"/.exec(svg);
  const paths = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((x) => x[1]);
  // Only plain shapes: path data holds nothing but numbers and drawing letters.
  if (!box || !paths.length || paths.some((d) => !/^[MmLlHhVvCcSsQqTtAaZz0-9eE\s,.\-+]+$/.test(d))) { skipped++; continue; }
  const shape = paths.join(" ");
  const name = f.slice(0, -4);
  const key = `${box[1]} ${box[2]} ${shape}`;
  if (!byShape.has(key)) byShape.set(key, { w: Number(box[1]), h: Number(box[2]), shape, names: [] });
  byShape.get(key).names.push(name);
}
// One entry per shape, under its current name; older names become search words.
const icons = {};
for (const it of byShape.values()) {
  const main = it.names.find((n) => m[n]) || it.names[0];
  const words = new Set(((m[main] && m[main].search && m[main].search.terms) || []).map((t) => String(t).toLowerCase()));
  for (const n of it.names) if (n !== main) words.add(n.replace(/-/g, " "));
  icons[main] = [it.w, it.h, it.shape, [...words].join(" ")];
}
const sorted = Object.fromEntries(Object.entries(icons).sort((a, b) => a[0].localeCompare(b[0])));
const version = /Font Awesome Free ([\d.]+)/.exec(readFileSync(`${dir}/folder.svg`, "utf8"))[1];
writeFileSync(out,
  `// Font Awesome Free ${version} by @fontawesome - https://fontawesome.com\n` +
  `// License - https://fontawesome.com/license/free (Icons: CC BY 4.0). Copyright Fonticons, Inc.\n` +
  `// The solid icons, as [width, height, shape, search words]. Generated by docs/build_fa.mjs; do not edit.\n` +
  `window.DC_FA = ${JSON.stringify({ version, icons: sorted })};\n`);
console.log(Object.keys(sorted).length, "icons,", skipped, "skipped,", version);
